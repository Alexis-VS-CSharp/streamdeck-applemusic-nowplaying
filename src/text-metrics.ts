const UNKNOWN_GLYPH_EM = 1; // CJK, emoji...: larges, on prefere surestimer

/** Largeur estimee en pixels de `text` a `fontPx` (semibold=true pour weight 600). */
export function textWidthPx(text: string, fontPx: number, semibold: boolean): number {
	let em = 0;
	for (const ch of text) {
		em += GLYPH_EM[ch]?.[semibold ? 1 : 0] ?? UNKNOWN_GLYPH_EM;
	}
	return em * fontPx;
}
